const TIDE_SQUARE_COMPANY = '타이드스퀘어';

function parseCareerBoundary(
  token: string,
  fallback: Date,
  boundary: 'start' | 'end',
): Date {
  const trimmed = token.trim();

  if (!trimmed || /재직/.test(trimmed)) {
    return fallback;
  }

  const match = trimmed.match(/(\d{4})\.(\d{1,2})/);

  if (!match) {
    return fallback;
  }

  const year = Number(match[1]);
  const month = Number(match[2]);
  const day = boundary === 'start' ? 1 : 0;

  return boundary === 'start'
    ? new Date(year, month - 1, day)
    : new Date(year, month, day);
}

function parseCareerPeriod(period: string, now = new Date()) {
  const [startToken = '', endToken = '재직중'] = period.split(/\s*-\s*/);

  return {
    start: parseCareerBoundary(startToken, now, 'start'),
    end: parseCareerBoundary(endToken, now, 'end'),
  };
}

function monthsBetween(start: Date, end: Date) {
  return Math.max(
    0,
    (end.getFullYear() - start.getFullYear()) * 12 +
      (end.getMonth() - start.getMonth()),
  );
}

function toYears(months: number, round: 'floor' | 'ceil') {
  if (months <= 0) {
    return 0;
  }

  const years = months / 12;

  return round === 'ceil' ? Math.ceil(years) : Math.floor(years);
}

/** total: 첫 경력 시작부터 현재까지의 만 년, frontend: 타이드스퀘어 근속(만 년) + 1 */
export function getCareerExperienceYears(
  items: CareerItem[],
  now = new Date(),
) {
  const ranges = items.map((item) => parseCareerPeriod(item.period, now));
  const tideIndex = items.findIndex((item) =>
    item.company.includes(TIDE_SQUARE_COMPANY),
  );
  const tideMonths =
    tideIndex >= 0
      ? monthsBetween(ranges[tideIndex].start, ranges[tideIndex].end)
      : 0;
  const totalMonths = ranges.length
    ? monthsBetween(
        new Date(Math.min(...ranges.map((range) => range.start.getTime()))),
        new Date(Math.max(...ranges.map((range) => range.end.getTime()))),
      )
    : 0;

  return {
    total: toYears(totalMonths, 'floor'),
    frontend: toYears(tideMonths, 'floor') + 1,
  };
}

