export const featuredFeProjectSlugs = [
  'promotion-deployment-platform',
  'ai-builder',
  'marketing-v0-seo-routing',
  'figma-email-builder',
  'tourvis-mypage-renewal',
  'common-ui-design-system',
];

export async function getFeaturedProjects(
  type: ProjectType,
  limit = 4,
): Promise<ProjectItem[]> {
  if (type === 'fe') {
    return featuredFeProjectSlugs
      .map(slug => feProjects.find(project => project.slug === slug))
      .filter((project): project is FeProjectItem => Boolean(project))
      .slice(0, limit);
  }

  const publishProjects = await getPublishProjects();
  return publishProjects.slice(0, limit);
}

export async function getProjectsByType(
  type: ProjectType,
): Promise<ProjectItem[]> {
  if (type === 'fe') {
    return sortProjectsByDate(feProjects);
  }

  return getPublishProjects();
}

export async function getProjectDetail(
  type: ProjectType,
  slug: string,
): Promise<ProjectItem | null> {
  const projects = await getProjectsByType(type);
  return projects.find((project) => project.slug === slug) ?? null;
}
